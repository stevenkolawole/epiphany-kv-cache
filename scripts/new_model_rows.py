"""LaTeX rows for the new-model tables (Qwen3-8B, Qwen3-14B, Nemotron-Nano-8B; H200, greedy, cap 16,384), from the
cells pooled by grid_tables.load(). Cells are accuracy on the problems every row of that model shares. Bold: best
eviction row in a column. Dagger on the EpiKV row: EpiKV is significantly above every attention-based row
in that column (exact McNemar p<0.05), including the R-KV and LongFlow rows that only the full tables print.

  new_model_rows.py main          MATH-500 at K=512, 1024, 4096; every row but LongFlow
  new_model_rows.py full math     every row and budget, MATH-500
  new_model_rows.py full gpqa     every row and budget, GPQA-Diamond
"""
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
from grid_tables import load, pair  # noqa: E402
from pool_aime import mcnemar_exact  # noqa: E402
import released_baselines  # noqa: E402

MODELS = ["qwen3", "q14b", "nemo"]
TEX = {"none": "none$^{\\star}$", "epikv": "\\methodq~(ours)", "epikvnoq": "\\methodseg~(no query term)", "lagkv": "Lag-KV",
       "raas": "RaaS", "h2o": "H2O", "rkv": "R-KV", "longflow": "LongFlow", "thinkv": "ThinKV"}
FA2 = {"none", "epikv", "epikvnoq", "lagkv"}
mode = sys.argv[1]
ds = "math" if mode == "main" else sys.argv[2]
KS = [512, 1024, 4096] if mode == "main" else ([512, 1024, 2048, 4096] if ds == "math" else [1024, 2048, 4096])
ROWS = ["none", "epikv", "epikvnoq", "lagkv", "raas", "h2o", "rkv", "thinkv"] if mode == "main" else \
       ["none", "epikv", "epikvnoq", "lagkv", "raas", "h2o", "rkv", "longflow", "thinkv"]
ATTENTION = ["raas", "h2o", "rkv", "longflow", "thinkv"]
cells, _, _ = load()
MARK = released_baselines.apply(cells, ds, MODELS, KS)   # R-KV from its released code; cells with no released number
def have(m, p, k):
    return (ds, m, p, 0 if p == "none" else k) in cells
ROWS = [p for p in ROWS if p in ("rkv", "longflow") or all(have(m, p, KS[0]) for m in MODELS)]
probs = {}
for m in MODELS:
    s = None
    for p in ROWS:
        for k in ([0] if p == "none" else KS):
            if not have(m, p, k):
                continue
            v = set(cells[(ds, m, p, 0 if p == "none" else k)])
            s = v if s is None else s & v
    probs[m] = sorted(s)
acc = {(m, p, k): 100 * sum(cells[(ds, m, p, 0 if p == "none" else k)][q]["correct"] for q in probs[m]) / len(probs[m])
       for m in MODELS for p in ROWS for k in KS if have(m, p, k)}
best = {(m, k): max(acc[(m, p, k)] for p in ROWS if p != "none" and have(m, p, k)) for m in MODELS for k in KS}
print(f"% generated by scripts/new_model_rows.py {' '.join(sys.argv[1:])}; n = " + ", ".join(f"{m} {len(probs[m])}" for m in MODELS))
for p in ROWS:
    mark = "\\cmark" if p in FA2 else "\\xmark"
    if p == "none":
        print(f"{TEX[p]} & {mark} & " + " & ".join(f"\\multicolumn{{{len(KS)}}}{{c}}{{{acc[(m, p, KS[0])]:.1f}}}" for m in MODELS) + " \\\\")
        print("\\midrule"); continue
    row = []
    for m in MODELS:
        for k in KS:
            if not have(m, p, k):
                row.append(MARK[(m, p, k)])
                continue
            c = f"{acc[(m, p, k)]:.1f}"
            if abs(acc[(m, p, k)] - best[(m, k)]) < 1e-9:
                c = f"\\textbf{{{c}}}"
            if p == "epikv":
                sig = []
                for t in [r for r in ATTENTION if (ds, m, r, k) in cells]:
                    w, l = pair(cells[(ds, m, "epikv", k)], cells[(ds, m, t, k)], probs[m])
                    sig.append(len(w) > len(l) and mcnemar_exact(len(w), len(l)) < 0.05)
                if sig and all(sig):
                    c += "$^{\\dagger}$"
            row.append(c)
    if p == "epikv":
        print("\\rowcolor{epirow}")
    print(f"{TEX[p]} & {mark} & " + " & ".join(row) + " \\\\")
    if p == "lagkv":
        print("\\midrule")

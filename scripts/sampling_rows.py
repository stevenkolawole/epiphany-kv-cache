"""LaTeX rows for the sampled-decoding appendix (MATH-500, temperature 0.6, top-p 0.95, one sampled seed per run).

Records: results/rebuttal_sampling (Babel L40S; prefixes samp = seed 0, samp1 = seed 1, samp16k = seed 0 at a 16,384
cap) and results/rebuttal_sampling_seed2_p4d (A100; samp2 = seed 2); 25-problem shards, 8,192-token cap unless stated.
A cell must have every shard, no partial block, no error and no 0-token problem. Stars: exact McNemar against EpiKV on
the same problems (* p<0.05, ** p<0.01, *** p<0.001).

  sampling_rows.py table      seed 0, cap 8,192: none, EpiKV, EpiKV^-Q, RaaS (the sampling table); stars against EpiKV
  sampling_rows.py seeds      EpiKV and RaaS accuracy, wins/losses and star per seed and cap, K = 512..4096
"""
import json
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
from grid_tables import pair, star  # noqa: E402
from pool_aime import mcnemar_exact  # noqa: E402

R = Path(__file__).resolve().parent.parent / "results"
RUNS = {"seed 0": (R / "rebuttal_sampling", "samp", 8192), "seed 1": (R / "rebuttal_sampling", "samp1", 8192),
        "seed 2": (R / "rebuttal_sampling_seed2_p4d", "samp2", 8192), "seed 0, 16k": (R / "rebuttal_sampling", "samp16k", 16384)}
SEED = {"samp": 0, "samp1": 1, "samp2": 2, "samp16k": 0}
PLATFORM = {"seed 0": "Babel L40S", "seed 1": "Babel L40S", "seed 2": "p4d A100", "seed 0, 16k": "Babel L40S"}
MODELS = {"llama": "Llama-8B", "qwen": "Qwen-7B"}
KS = [512, 1024, 2048, 4096]


def cell(run, model, method, K):
    d, pre, cap = RUNS[run]
    out = {}
    for s in range(0, 500, 25):
        j = json.load(open(d / f"{pre}_{model}_{method}_K{K}_s{s}.json"))
        assert j["meta"]["max_new_tokens"] == cap and j["meta"]["sampling"]["top_p"] == 0.95 and j["meta"]["sampling"]["temperature"] == 0.6
        assert j["meta"]["sampling"]["seed"] == SEED[pre], (pre, j["meta"]["sampling"])
        e = next(iter(next(iter(j["results"].values())).values()))
        assert not e.get("partial"), (pre, model, method, K, s)
        for i, p in enumerate(e["per_problem"]):
            assert not p.get("error") and p["n_tokens_generated"], (pre, model, method, K, s, i)
            out[s + i] = p
    return out


def stars(pv):
    s = star(pv)
    return f"$^{{{s}}}$" if s else ""


def table():
    run = "seed 0"
    c = {(m, p, K): cell(run, m, p, 1024 if p == "none" else K) for m in MODELS for p in ("none", "epikv", "epikvnoq", "raas") for K in KS}
    n = {len(v) for v in c.values()}
    assert len(n) == 1, n
    probs = sorted(c[("llama", "epikv", 512)])
    for m in MODELS:   # same problems in every cell of a model
        assert all(sorted(c[(m, p, K)]) == probs for p in ("none", "epikv", "epikvnoq", "raas") for K in KS)
    acc = lambda m, p, K: 100 * sum(c[(m, p, K)][q]["correct"] for q in probs) / len(probs)
    print(f"% generated by scripts/sampling_rows.py table; seed 0, cap 8192, {PLATFORM[run]}, n = {len(probs)}; stars: exact McNemar against EpiKV")
    print("none$^{\\star}$ & " + " & ".join(f"\\multicolumn{{4}}{{c}}{{{acc(m, 'none', 1024):.1f}}}" for m in MODELS) + " \\\\")
    print("\\midrule")
    for p, name in (("epikv", "\\methodq"), ("epikvnoq", "\\methodseg~(no query term)"), ("raas", "RaaS")):
        row = []
        for m in MODELS:
            for K in KS:
                s = ""
                if p != "epikv":
                    w, l = pair(c[(m, "epikv", K)], c[(m, p, K)], probs)
                    s = stars(mcnemar_exact(len(w), len(l)))
                row.append(f"{acc(m, p, K):.1f}{s}")
        print(("\\rowcolor{epirow}" if p == "epikv" else "") + f"{name} & " + " & ".join(row) + " \\\\")


def seeds():
    print("% EpiKV vs RaaS under sampling per seed and cap; cells: EpiKV accuracy, RaaS accuracy, EpiKV wins/losses (exact McNemar star); "
          "n = 495; platforms: " + "; ".join(f"{r}: {PLATFORM[r]}" for r in RUNS))
    for m, mname in MODELS.items():
        for run in RUNS:
            row = []
            for K in KS:
                e, r = cell(run, m, "epikv", K), cell(run, m, "raas", K)
                probs = sorted(e)
                assert sorted(r) == probs
                w, l = pair(e, r, probs)
                a = lambda x: 100 * sum(x[q]["correct"] for q in probs) / len(probs)
                row.append(f"{a(e):.1f} & {a(r):.1f} & {len(w)}/{len(l)}{stars(mcnemar_exact(len(w), len(l)))}")
            print(f"{mname} & {run} ({PLATFORM[run]}) & " + " & ".join(row) + f" \\\\ % n={len(probs)}")


{"table": table, "seeds": seeds}[sys.argv[1]]()

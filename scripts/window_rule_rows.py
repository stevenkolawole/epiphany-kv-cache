"""LaTeX rows for the appendix table of released baselines and of the RaaS and R-KV rules on EpiKV's query read.

Reads results/rebuttal_window_rules/paired_with_epikv.txt (written by scripts/pair_with_epikv.py from the Babel
cells: MATH-500, n=495, greedy, cap 16,384). Each row's cells are accuracy; a star marks a paired difference from
EpiKV on the same problems (exact McNemar, * p<0.05, ** p<0.01, *** p<0.001). Usage: window_rule_rows.py
"""
import re
from pathlib import Path

F = Path(__file__).resolve().parent.parent / "results" / "rebuttal_window_rules" / "paired_with_epikv.txt"
ROWS = [("raas_epikv_window", "RaaS's rule on the query read"), ("r_kv_epikv_window", "R-KV's rule on the query read"),
        ("kvpress_snapkv_decoding", "kvpress (SnapKV, decoding)"), ("longflow_native", "LongFlow (released kernel)")]
KS = [512, 1024, 2048, 4096]
acc, epi, p = {}, {}, {}
for line in F.read_text().splitlines():
    m = re.match(r"(llama|qwen)_(\w+)_K(\d+)\s+(\d+)\s+([\d.]+)\s+([\d.]+)\s+\d+\s+\d+\s+([\d.]+)", line)
    if not m:
        continue
    model, meth, K, n, a, e, pv = m.group(1), m.group(2), int(m.group(3)), int(m.group(4)), *map(float, m.group(5, 6, 7))
    assert n == 495, line
    acc[(model, meth, K)], p[(model, meth, K)] = a, pv
    epi.setdefault((model, K), set()).add(e)
print("% generated by scripts/window_rule_rows.py from results/rebuttal_window_rules/paired_with_epikv.txt")
cells = []
for model in ("llama", "qwen"):
    for K in KS:
        v = epi[(model, K)]
        assert len(v) == 1, (model, K, v)   # EpiKV's accuracy is the same in every pairing
        cells.append(f"{v.pop():.1f}")
print("\\rowcolor{epirow}\\methodq & " + " & ".join(cells) + " \\\\")
print("\\midrule")
for meth, label in ROWS:
    cells = []
    for model in ("llama", "qwen"):
        for K in KS:
            if (model, meth, K) not in acc:
                cells.append("--"); continue
            pv = p[(model, meth, K)]
            star = "$^{***}$" if pv < 0.001 else "$^{**}$" if pv < 0.01 else "$^{*}$" if pv < 0.05 else ""
            cells.append(f"{acc[(model, meth, K)]:.1f}{star}")
    print(f"{label} & " + " & ".join(cells) + " \\\\")

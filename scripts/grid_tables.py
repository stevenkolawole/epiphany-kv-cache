#!/usr/bin/env python3
"""Pooled tables and checks for the new-model grids (Qwen3-14B, Qwen3-8B, Nemotron-Nano-8B), all H200.

Pools every shard file of a (dataset, model, method, K) into one cell, paired on problem text.
Sources (H200 only; A100 files from p4d are left out):
  results/aws_grid_nov2026/p5/results_{nemo_h200,baselines,gpqa_qwen3_h200}  (Oct 28 queue)
  results/aws_grid_oct2026/p5/results_{newmodels,qwen3,gpqa_new}  (Qwen3 none/EpiKV/seg/LagKV/RaaS)
Nemotron comes from the Oct 28 H200 rerun only; its Oct A100 cells are not read.

A file counts only when no block is partial and no problem has an error or 0 generated tokens.
A cap hit is an error whose generation reached the cap. Paired tests are exact McNemar.

  python3 scripts/grid_tables.py            # markdown report to stdout
"""
import collections
import glob
import json
import os
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from pool_aime import mcnemar_exact  # noqa: E402

R = Path(__file__).resolve().parent.parent / "results"
SOURCES = [R / "aws_grid_nov2026/p5" / d for d in ("results_nemo_h200", "results_baselines", "results_gpqa_qwen3_h200")]
SOURCES += [R / "aws_grid_oct2026/p5" / d for d in ("results_newmodels", "results_qwen3", "results_gpqa_new")]
CAP = 16384
PAT = re.compile(r"^(?:h200_)?(?P<ds>math|gpqa)_(?P<m>q14b|qwen3|nemo)_(?P<p>[a-z0-9_]+?)_K(?P<k>\d+)_s(?P<s>\d+)\.json$")
NAME = {"lag_kv": "lagkv", "r_kv": "rkv", "thinkv_faithful": "thinkv"}
MODELS = {"q14b": "Qwen3-14B", "qwen3": "Qwen3-8B", "nemo": "Nemotron-Nano-8B"}
ORDER = ["none", "epikv", "epikvnoq", "seg", "raas", "h2o", "rkv", "longflow", "lagkv", "thinkv"]
LABEL = {"none": "none", "epikv": "EpiKV", "epikvnoq": "EpiKV^-Q", "seg": "seg (EpiKV w/o fill)",
         "raas": "RaaS", "h2o": "H2O", "rkv": "R-KV", "longflow": "LongFlow", "lagkv": "LagKV",
         "thinkv": "ThinKV"}


def complete(d):
    for cells in d["results"].values():
        for cell in cells.values():
            pp = cell.get("per_problem") or []
            if cell.get("partial") or not pp:
                return False
            if any(p.get("error") or not p.get("n_tokens_generated") for p in pp):
                return False
    return True


def load():
    cells = collections.defaultdict(dict)  # (ds, m, p, K) -> dataset index -> record
    log = collections.Counter()
    dups = []
    for src in SOURCES:
        for f in sorted(glob.glob(str(src / "*.json"))):
            mm = PAT.match(os.path.basename(f))
            if not mm:
                log["unmatched name"] += 1
                continue
            if mm["m"] == "nemo" and "oct2026" in f:
                log["oct nemo (stale, replaced by H200 rerun)"] += 1
                continue
            d = json.load(open(f))
            if not complete(d):
                log[f"incomplete: {src.name}/{mm['ds']}_{mm['m']}"] += 1
                continue
            log["complete files read"] += 1
            p = NAME.get(mm["p"], mm["p"])
            for cs in d["results"].values():
                for k, cell in cs.items():
                    key = (mm["ds"], mm["m"], p, 0 if p == "none" else int(k))
                    for i, r in enumerate(cell["per_problem"]):
                        q = int(mm["s"]) + i  # dataset index; the text is checked against other cells below
                        old = cells[key].get(q)
                        if old is not None:
                            dups.append((key, old["correct"] == r["correct"], f))
                            continue
                        cells[key][q] = r
    texts = collections.defaultdict(set)  # (ds, index) -> problem texts seen
    for (ds, m, p, k), c in cells.items():
        for q, r in c.items():
            texts[(ds, q)].add(r["problem"])
    log["dataset indices whose problem text differs between cells"] = sum(len(v) > 1 for v in texts.values())
    return cells, log, dups


def stats(rs):
    n = len(rs)
    err = [r for r in rs if not r["correct"]]
    cap = sum(r["n_tokens_generated"] >= CAP for r in err)
    noans = sum(r["n_tokens_generated"] < CAP and r["pred_answer"] in (None, "") for r in err)
    return n, sum(r["correct"] for r in rs), len(err), cap, noans


def pair(a, b, probs):
    w = [q for q in probs if a[q]["correct"] and not b[q]["correct"]]
    l = [q for q in probs if b[q]["correct"] and not a[q]["correct"]]
    return w, l


def star(p):
    return "***" if p < .001 else "**" if p < .01 else "*" if p < .05 else ""


def main():
    cells, log, dups = load()
    print("# New-model grids, pooled (generated by scripts/grid_tables.py)\n")
    print("## Load log\n")
    for k, v in sorted(log.items()):
        print(f"- {k}: {v}")
    same = sum(x[1] for x in dups)
    print(f"- duplicate problem records (same cell, two files): {len(dups)}, same correctness {same}")
    for (ds, m) in [(ds, m) for ds in ("math", "gpqa") for m in MODELS]:
        ks = sorted({k for (d_, m_, p, k) in cells if d_ == ds and m_ == m and k})
        meths = [p for p in ORDER if any((ds, m, p, k) in cells for k in ks + [0])]
        if not meths:
            continue
        none = cells.get((ds, m, "none", 0), {})
        allp = set(none)
        for p in meths:
            for k in ([0] if p == "none" else ks):
                if (ds, m, p, k) in cells:
                    allp &= set(cells[(ds, m, p, k)])
        probs = sorted(allp)
        title = "MATH-500" if ds == "math" else "GPQA-Diamond"
        print(f"\n## {title}, {MODELS[m]}\n")
        print(f"Paired set: n = {len(probs)} problems present in every cell below "
              f"(cell sizes: " + ", ".join(sorted({str(len(v)) for (d_, m_, p, k), v in cells.items()
                                                     if d_ == ds and m_ == m})) + ").\n")
        print("Accuracy % (cap hits as % of problems).\n")
        print("| method | " + " | ".join(f"K={k}" for k in ks) + " |")
        print("|---|" + "---|" * len(ks))
        for p in meths:
            row = []
            for k in ks:
                c = cells.get((ds, m, p, 0 if p == "none" else k))
                if not c:
                    row.append("")
                    continue
                n, ok, e, cap, _ = stats([c[q] for q in probs])
                row.append(f"{100 * ok / n:.1f} ({100 * cap / n:.0f})")
            print(f"| {LABEL[p]} | " + " | ".join(row) + " |")
        ep = "epikv"
        print(f"\nEpiKV vs each, paired wins/losses (exact McNemar p):\n")
        print("| vs | " + " | ".join(f"K={k}" for k in ks) + " |")
        print("|---|" + "---|" * len(ks))
        for p in meths:
            if p == ep:
                continue
            row = []
            for k in ks:
                a, b = cells.get((ds, m, ep, k)), cells.get((ds, m, p, 0 if p == "none" else k))
                if not a or not b:
                    row.append("")
                    continue
                w, l = pair(a, b, probs)
                pv = mcnemar_exact(len(w), len(l))
                row.append(f"{len(w)}/{len(l)}{star(pv)} (p={pv:.3g})")
            print(f"| {LABEL[p]} | " + " | ".join(row) + " |")
        print(f"\nErrors split by termination: errors / cap hits / terminated wrong "
              f"(of which stopped with no extractable answer).\n")
        print("| method | " + " | ".join(f"K={k}" for k in ks) + " |")
        print("|---|" + "---|" * len(ks))
        for p in meths:
            row = []
            for k in ks:
                c = cells.get((ds, m, p, 0 if p == "none" else k))
                if not c:
                    row.append("")
                    continue
                n, ok, e, cap, noans = stats([c[q] for q in probs])
                row.append(f"{e} / {cap} / {e - cap} ({noans})")
            print(f"| {LABEL[p]} | " + " | ".join(row) + " |")
        if none:
            print(f"\nErrors added over none (right without eviction, wrong under the policy; "
                  f"in parentheses, how many of those hit the cap):\n")
            print("| method | " + " | ".join(f"K={k}" for k in ks) + " |")
            print("|---|" + "---|" * len(ks))
            for p in meths:
                if p == "none":
                    continue
                row = []
                for k in ks:
                    c = cells.get((ds, m, p, k))
                    if not c:
                        row.append("")
                        continue
                    added = [q for q in probs if none[q]["correct"] and not c[q]["correct"]]
                    capped = sum(c[q]["n_tokens_generated"] >= CAP for q in added)
                    row.append(f"{len(added)} ({capped})")
                print(f"| {LABEL[p]} | " + " | ".join(row) + " |")


if __name__ == "__main__":
    main()

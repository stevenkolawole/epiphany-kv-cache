"""LaTeX rows for the appendix table of controls on the Table 2 stack: the key norm, prompt-protected random eviction,
and EpiKV with a strict trigger (cache never above K). MATH-500, n=495, greedy, cap 8192; records results/rebuttal_p4d
(25 shards of 20 problems). Cells are accuracy; a star marks a paired difference from the EpiKV row of Table 2 on the
same problems (exact McNemar). Strict EpiKV at K=512 compacts every 32 steps at budget 480; at larger K it runs at
budget K-128. Usage: control_rows.py
"""
import json, sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
from acc_tables import MATH_DIRS, KS_MATH, pair  # noqa: E402
from n500_table import cells  # noqa: E402

R = Path(__file__).resolve().parent.parent / "results" / "rebuttal_p4d"
ROWS = [("knorm", "Key norm"), ("random", "Random, prompt and recent tokens kept"), ("strict", "\\methodq, cache never above $K$")]


def cell(model, tag, K):
    if tag == "strict":
        tag = "epikvstrict32" if K == 512 else "epikvstrict"
    v = []
    for S in range(0, 500, 20):
        j = json.load(open(R / f"math_{model}_{tag}_K{K}_s{S}.json"))["results"]
        e = next(iter(next(iter(j.values())).values()))
        assert not e.get("partial"), (model, tag, K, S)
        v += [bool(p["correct"]) for p in e["per_problem"]]
    assert len(v) == 495, (model, tag, K, len(v))
    return v


print("% generated by scripts/control_rows.py from results/rebuttal_p4d")
epi = {("llama" if "llama" in d else "qwen"): cells(d, "llama" if "llama" in d else "qwen", "epikv_q") for d in MATH_DIRS.values()}
print("\\rowcolor{epirow}\\methodq~(Table~\\ref{tab:acc-math}) & " + " & ".join(f"{100 * sum(epi[m][K]) / len(epi[m][K]):.1f}" for m in ("llama", "qwen") for K in KS_MATH) + " \\\\")
print("\\midrule")
for tag, label in ROWS:
    row = []
    for model in ("llama", "qwen"):
        for K in KS_MATH:
            v = cell(model, tag, K)
            w, l, pv = pair(epi[model][K], v)
            star = "$^{***}$" if pv < 0.001 else "$^{**}$" if pv < 0.01 else "$^{*}$" if pv < 0.05 else ""
            row.append(f"{100 * sum(v) / len(v):.1f}{star}")
    print(f"{label} & " + " & ".join(row) + " \\\\")

"""LaTeX rows for the serving table (Llama-8B, one A100-SXM4-40GB, each policy at its largest batch), from
results/rebuttal_baseline_costs/records via baseline_cost_tables.load. Units are in the column heads, not the cells.

  serving_rows.py main     step ms (batch 1, K=4096; median of steady windows), requests and tokens/s per card at
                           K=2048 and K=4096 (largest batch that ran 512 steps, tput_* records; tokens/s = batch x
                           1000 / median ms per step), compaction ms and transient GB (8,192-token cache to 4,096,
                           batch 1; median ms, max transient). RaaS and H2O evict every step: no compaction cell.
  serving_rows.py none     no eviction at 8k, 16k and 32k context: requests, tokens/s
"""
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
from baseline_cost_tables import load, med  # noqa: E402

recs = dict(load(Path(__file__).resolve().parent.parent / "results" / "rebuttal_baseline_costs" / "records"))
# (label, steady/compaction record, throughput record at K=2048, at K=4096)
ROWS = [("\\rowcolor{epirow}\\methodq", "epikv_batched", "tput_epikv_batched_fresh_K2048_B80", "tput_epikv_batched_fresh_K4096"),
        ("kvpress (SnapKV, decoding)", "snapkv_decoding", "tput_snapkv_decoding_K2048", "tput_snapkv_decoding_K4096"),
        ("R-KV (released code)", "rkv", "tput_rkv_K2048", "tput_rkv_K4096"),
        ("RaaS", "raas", "tput_raas_K2048", "tput_raas_K4096"),
        ("H2O", "h2o", "tput_h2o_K2048", "tput_h2o_K4096")]


def tput(name):
    """(batch, tokens/s) of the cell that ran; every OOM cell in the record must be a larger batch."""
    ok = [c for c in recs[name]["cells"].values() if "oom" not in c]
    assert len(ok) == 1 and all(c["batch"] > ok[0]["batch"] for c in recs[name]["cells"].values() if "oom" in c), name
    c = ok[0]
    assert recs[name]["meta"]["finished"] and recs[name]["meta"]["gpu"] == "NVIDIA A100-SXM4-40GB"
    return c["batch"], c["batch"] * 1000 / med(w["ms_per_token"] for w in c["windows"])


if sys.argv[1] == "main":
    print("% generated by scripts/serving_rows.py main; Llama-8B, A100-SXM4-40GB")
    for label, m, t2, t4 in ROWS:
        step = med(w["ms_per_token"] for w in recs[f"steady_{m}"]["cells"]["K4096_B1"]["windows"])
        row = [f"{step:.1f}"]
        for t in (t2, t4):
            b, ts = tput(t)
            row += [str(b), f"{ts:.0f}"]
        if m in ("raas", "h2o"):
            row += ["--", "--"]
        else:
            r = recs[f"compaction_{m}"]["cells"]["L8192_K4096_B1"]["repeats"]
            row += [f"{med(x['ms'] for x in r):.0f}", f"{max(x['transient_gb'] for x in r):.2f}"]
        print(f"{label} & " + " & ".join(row) + " \\\\")
else:
    print("% generated by scripts/serving_rows.py none; no eviction, Llama-8B, A100-SXM4-40GB; context, requests, tokens/s")
    for L in (8192, 16384, 32768):
        b, ts = tput(f"tput_none_K{L}")
        print(f"{L // 1024}k & {b} & {ts:.0f} \\\\")

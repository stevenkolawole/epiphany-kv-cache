#!/usr/bin/env python3
"""Figure 3 (fig:layers) and the per-layer table (tab:perlayer), both from the recovered
signal-ablation CSVs, which are the paper's source data (results_recovered/ANALYSIS.md):

  results_recovered/{math500,math500_eager,aime2024,aime2024_eager}_signal_ablation.csv

Per layer l the value is Spearman rho of hs_l2_diff_l{l}_rolling64 with the counterfactual
importance labels (EOS filler).  Also prints the cumulative-attention comparison rows
(tab:attnsignal): h2o_attn and attn_entropy against the deployed band layers, eager datasets only.

  python scripts/plot_layer_rho.py --wrap --figure ../EpiKV-overleaf/figures/layer_rho.pdf
  python scripts/plot_layer_rho.py --perlayer > ../EpiKV-overleaf/tables/tab_perlayer_rows.tex
  python scripts/plot_layer_rho.py --attn     > ../EpiKV-overleaf/tables/tab_attnsignal_rows.tex
"""
import argparse
import csv
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import figstyle  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
CSV = ROOT / "results_recovered"
SETS = [("math500", "MATH-500"), ("math500_eager", "MATH-500 (eager)"),
        ("aime2024", "AIME-2024"), ("aime2024_eager", "AIME-2024 (eager)")]
BAND_A, BAND_B = (7, 13), (18, 25)


def load(name):
    d = {}
    with open(CSV / f"{name}_signal_ablation.csv") as f:
        for r in csv.DictReader(f):
            d[r["signal"]] = float(r["spearman_rho"])
    return d


def rho(d, l):
    return d[f"hs_l2_diff_l{l}_rolling64"]


def fmt(x):
    return ("$+$" if x >= 0 else "$-$") + f"{abs(x):.3f}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--figure", type=Path)
    ap.add_argument("--perlayer", action="store_true")
    ap.add_argument("--attn", action="store_true")
    ap.add_argument("--compact", action="store_true", help="half-width version for a wrapped figure")
    ap.add_argument("--wrap", action="store_true",
                    help="the main-text wrapped figure: MATH-500 only (the configurations the per-layer claim rests on), "
                         "0.42 text width, neutral band shading, the two deployed layers marked")
    a = ap.parse_args()
    data = {k: load(k) for k, _ in SETS}
    if a.perlayer:
        print("% per-layer Spearman rho of rolling-64 hidden-state change with importance labels; generated by scripts/plot_layer_rho.py --perlayer")
        for l in range(32):
            lab = f"\\textbf{{{l}}}" if BAND_A[0] <= l <= BAND_A[1] or BAND_B[0] <= l <= BAND_B[1] else str(l)
            print(lab + " & " + " & ".join(fmt(rho(data[k], l)) for k, _ in SETS) + " \\\\")
    if a.attn:
        print("% cumulative attention against the deployed band layers, eager datasets; generated by scripts/plot_layer_rho.py --attn")
        for k, name in SETS:
            if "eager" not in k:
                continue
            d = data[k]
            print(name.replace(" (eager)", "") + " & " + " & ".join(fmt(v) for v in (d["h2o_attn"], d["attn_entropy"], rho(d, 10), rho(d, 21), d["kv_key_var_rolling64"])) + " \\\\")
    if a.figure and a.wrap:
        figstyle.use()
        import matplotlib.pyplot as plt
        fig, ax = plt.subplots(figsize=(figstyle.TEXT_W * 0.39, 1.38))
        for (lo, hi), shade in ((BAND_A, figstyle.BAND_A), (BAND_B, figstyle.BAND_B)):
            ax.axvspan(lo - 0.5, hi + 0.5, color=shade, lw=0, zorder=0)
        ax.axhline(0, color=figstyle.GREY, lw=0.5, zorder=1)
        xs = list(range(32))
        # MATH-500 traces under FlashAttention only (Steven, Sep 24): the eager traces are a separate
        # generation, and beside this line they read as a kernel effect; both are in tab:perlayer
        fa = [rho(data["math500"], l) for l in xs]
        ax.plot(xs, fa, color=figstyle.INK, lw=1.2, zorder=3)
        for l in (10, 21):  # the two layers s(t) reads
            ax.plot([l], [rho(data["math500"], l)], "o", ms=3.8, color=figstyle.BLUE, zorder=4)
        ax.text(sum(BAND_A) / 2, 0.215, "Band A", ha="center", va="bottom", fontsize=7, color=figstyle.INK)
        ax.text(sum(BAND_B) / 2, 0.215, "Band B", ha="center", va="bottom", fontsize=7, color=figstyle.INK)
        ax.set_xlim(-0.5, 31.5)
        ax.set_ylim(-0.29, 0.27)
        ax.set_yticks([-0.2, 0, 0.2])
        ax.set_yticklabels(["$-$0.2", "0", "0.2"])
        ax.set_xticks([0, 7, 13, 18, 25, 31])
        ax.set_xlabel("layer", labelpad=1)
        ax.set_ylabel(r"Spearman $\rho$", labelpad=1)
        a.figure.parent.mkdir(parents=True, exist_ok=True)
        fig.savefig(a.figure)
        print("wrote", a.figure, file=sys.stderr)
        return
    if a.figure:
        figstyle.use()
        import matplotlib.pyplot as plt
        fig, ax = plt.subplots(figsize=(figstyle.TEXT_W * (0.46 if a.compact else 0.85), 2.25 if a.compact else 2.6))
        ax.axvspan(BAND_A[0] - 0.5, BAND_A[1] + 0.5, color=figstyle.BLUE_LIGHT, alpha=0.5, lw=0)
        ax.axvspan(BAND_B[0] - 0.5, BAND_B[1] + 0.5, color=figstyle.RED_LIGHT, alpha=0.5, lw=0)
        ax.axhline(0, color=figstyle.GREY, lw=0.6)
        style = {"math500": (figstyle.INK, "-", "o"), "math500_eager": (figstyle.INK, "--", "s"),
                 "aime2024": (figstyle.GREY, "-", "^"), "aime2024_eager": (figstyle.GREY, "--", "D")}
        xs = list(range(32))
        for k, name in SETS:
            c, ls, mk = style[k]
            ys = [rho(data[k], l) for l in xs]
            ax.plot(xs, ys, color=c, ls=ls, marker=mk, ms=2.5, lw=1.1, label=name)
        ax.text(sum(BAND_A) / 2, 0.27, "Band A", color=figstyle.BLUE, ha="center", fontsize=7 if a.compact else 8)
        ax.text(sum(BAND_B) / 2, 0.27, "Band B", color=figstyle.RED, ha="center", fontsize=7 if a.compact else 8)
        ax.set_xlabel("layer")
        ax.set_ylabel(r"Spearman $\rho$ with importance")
        ax.set_xlim(-0.5, 31.5)
        ax.set_ylim(-0.3, 0.32)
        if a.compact:
            ax.set_ylabel(r"$\rho$ with importance")
            ax.set_xticks([0, 7, 13, 18, 25, 31])
            ax.legend(ncol=2, loc="upper center", bbox_to_anchor=(0.5, -0.24), fontsize=6.5,
                      columnspacing=0.8, handletextpad=0.4, handlelength=1.6)
        else:
            ax.legend(ncol=4, loc="upper center", bbox_to_anchor=(0.5, -0.22), fontsize=7,
                      columnspacing=1.2, handletextpad=0.5)
        a.figure.parent.mkdir(parents=True, exist_ok=True)
        fig.savefig(a.figure)
        print("wrote", a.figure, file=sys.stderr)


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""Components of EpiKV at the tight budgets (Appendix exhibit behind the future-work paragraph):
the query-blind Seg, the fill alone (by the frozen score), the query term alone (w=8, no fill),
a one-token query window with the fill, and the shipped EpiKV (w=8 + fill), on MATH-500 problems
0-99, both models, K=512 and 1024, with paired wins/losses and exact McNemar p against Seg.

Every cell is the tau=128 family on the platform of Table 2 (A100, transformers 4.57.1):
results/{llama,qwen}_logical (Seg), results/qk_p4d (fill-only, query-only, w=1 query-only) and
results/win (w=1+fill, w=8+fill).  Cells that were not run print as "--".

  python scripts/component_table.py            # markdown
  python scripts/component_table.py --latex    # rows for tables/tab_components_rows.tex
"""
import argparse
import json
from math import comb
from pathlib import Path

R = Path(__file__).resolve().parent.parent / "results"
MODELS = ["llama", "qwen"]
KS = [512, 1024]
ROWS = [  # (label, {model: {K: path relative to results/}})
    ("\\methodseg~(no query term, no fill)", lambda m, K: f"{m}_logical/kv_seg_hs_tau128_K{K}.json"),
    ("+ fill by $s(t)$, no query term", lambda m, K: f"qk_p4d/kv_seg_hs_fill_tau128_K{K}_{m}.json"),
    ("+ query term ($w{=}8$), no fill", lambda m, K: f"qk_p4d/kv_seg_hs_tau128_qk_w8rep_K{K}_{m}.json"),
    ("+ query term ($w{=}1$), no fill", lambda m, K: f"qk_p4d/kv_seg_hs_tau128_qk_w1rep_K{K}_{m}.json"),
    ("+ query term ($w{=}1$) + fill", lambda m, K: f"win/kv_seg_hs_fill_tau128_qk_w1rep_K{K}_{m}.json"),
    ("\\methodq~($w{=}8$ + fill)", lambda m, K: f"win/kv_seg_hs_fill_tau128_qk_w8rep_K{K}_{m}.json"),
]
ALT = {  # a cell that lives elsewhere under the same configuration
    ("win/kv_seg_hs_fill_tau128_qk_w8rep_K1024_llama.json"): "qk_p4d/kv_seg_hs_fill_tau128_qk_w8rep_K1024_llama.json",
}


def recs(rel):
    p = R / ALT.get(rel, rel)
    if not p.exists():
        return None
    j = json.load(open(p))
    m = next(iter(j["results"]))
    return j["results"][m][next(iter(j["results"][m]))]["per_problem"]


def mcnemar(w, l):
    n = w + l
    if n == 0:
        return 1.0
    k = min(w, l)
    return min(1.0, 2 * sum(comb(n, i) for i in range(k + 1)) / 2 ** n)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--latex", action="store_true")
    a = ap.parse_args()
    base = {(m, K): recs(f"{m}_logical/kv_seg_hs_tau128_K{K}.json") for m in MODELS for K in KS}
    out = []
    for label, path in ROWS:
        cells = []
        for m in MODELS:
            for K in KS:
                pp = recs(path(m, K))
                if pp is None:
                    cells.append("--")
                    continue
                acc = 100 * sum(x["correct"] for x in pp) / len(pp)
                b = base[(m, K)]
                assert len(b) == len(pp) == 100, (label, m, K, len(pp))
                w = sum(x["correct"] and not y["correct"] for x, y in zip(pp, b))
                l = sum(y["correct"] and not x["correct"] for x, y in zip(pp, b))
                p = mcnemar(w, l)
                star = "$^{***}$" if p < 0.001 else "$^{**}$" if p < 0.01 else "$^{*}$" if p < 0.05 else ""
                if label.startswith("\\methodseg"):
                    cells.append(f"{acc:.1f}")
                else:
                    cells.append(f"{acc:.1f} ({w}/{l}){star}" if a.latex else f"{acc:.1f} ({w}/{l}, p={p:.3f})")
        out.append((label, cells))
    if a.latex:
        print("% components of EpiKV, MATH-500 problems 0-99, tau=128; cells: accuracy (wins/losses vs Seg, exact McNemar stars)")
        print("% generated by scripts/component_table.py --latex")
        for label, cells in out:
            print(label + " & " + " & ".join(cells) + " \\\\")
    else:
        print("| variant | Llama 512 | Llama 1024 | Qwen 512 | Qwen 1024 |")
        print("|---|---|---|---|---|")
        for label, cells in out:
            print(f"| {label} | " + " | ".join(cells) + " |")


if __name__ == "__main__":
    main()

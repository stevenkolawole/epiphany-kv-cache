#!/usr/bin/env python3
"""Appendix B.4 (tab:bandw) under the paper protocol: EpiKV (fill + query term, tau=128 steps
rule, logical positions, FA2, Llama-8B, MATH-500 problems 0-99) with the band layers and the
rolling window perturbed around the deployed (10, 21, 64). Cells: accuracy, and in parentheses
paired wins/losses against the deployed setting on the same problems.

  python3 scripts/bandw_table.py --dir results/bandw_paper > ../EpiKV-overleaf/tables/tab_bandw_rows.tex
"""
import argparse, json
from math import comb
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
VARIANTS = [("A$-$2", "a8_b21_w64", (8, 21, 64)), ("A$+$2", "a12_b21_w64", (12, 21, 64)),
            ("B$-$2", "a10_b19_w64", (10, 19, 64)), ("B$+$2", "a10_b23_w64", (10, 23, 64)),
            ("both $-$2", "a8_b19_w64", (8, 19, 64)), ("both $+$2", "a12_b23_w64", (12, 23, 64)),
            ("window 32", "a10_b21_w32", (10, 21, 32)), ("window 128", "a10_b21_w128", (10, 21, 128))]
KS = (1024, 2048)


def per_problem(path):
    d = json.load(open(path))
    m = next(iter(d["results"]))
    c = d["results"][m][str(next(iter(d["results"][m])))]
    if "accuracy" not in c:          # the harness writes accuracy only when a cell completes
        return None
    return [bool(p["correct"]) for p in c["per_problem"]]


def mcnemar(w, l):
    n = w + l
    return 1.0 if n == 0 else min(1.0, 2 * sum(comb(n, i) for i in range(min(w, l) + 1)) / 2 ** n)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", type=Path, default=ROOT / "results" / "bandw_paper")
    a = ap.parse_args()
    dep = {K: per_problem(ROOT / "results" / "win" / f"kv_seg_hs_fill_tau128steps_qk_w8rep_K{K}_llama.json") for K in KS}
    print("% tab:bandw rows, paper protocol; generated by scripts/bandw_table.py")
    print("deployed & 10, 21, 64 & " + " & ".join(f"{100 * sum(dep[K]) / len(dep[K]):.1f}" for K in KS) + " \\\\")
    print("\\midrule")
    pmin = 1.0
    for name, tag, (x, y, w) in VARIANTS:
        cells = []
        for K in KS:
            f = a.dir / f"epikv_{tag}_K{K}_s0_llama.json"
            if not f.exists():
                cells.append("--"); continue
            v = per_problem(f)
            if v is None:
                cells.append("--"); continue
            wins = sum(1 for p, q in zip(v, dep[K]) if p and not q)
            losses = sum(1 for p, q in zip(v, dep[K]) if q and not p)
            pmin = min(pmin, mcnemar(wins, losses))
            cells.append(f"{100 * sum(v) / len(v):.1f} ({wins}/{losses})")
        print(f"{name} & {x}, {y}, {w} & " + " & ".join(cells) + " \\\\")
    print(f"% smallest exact McNemar p against the deployed setting: {pmin:.3f}")


if __name__ == "__main__":
    main()

"""Join the window-rule accuracy rows and cap-hit rows into one set: each cell is accuracy with the number of
generations that reach the cap in brackets.

  window_rule_merged_rows.py <accuracy rows .tex> <cap-hit rows .tex>
"""
import re
import sys

acc = [l.rstrip("\n") for l in open(sys.argv[1]) if not l.startswith("%")]
cap = [l.rstrip("\n") for l in open(sys.argv[2]) if not l.startswith("%")]
assert len(acc) == len(cap), (len(acc), len(cap))
print("% generated by scripts/window_rule_merged_rows.py from the rows of window_rule_rows.py and window_rule_caps.py")
for a, c in zip(acc, cap):
    if " & " not in a or a.startswith("\\multicolumn"):
        assert a == c, (a, c)
        print(a)
        continue
    ca, cc = a.rstrip("\\ ").split(" & "), c.rstrip("\\ ").split(" & ")
    assert ca[0] == cc[0] and len(ca) == len(cc), (ca[0], cc[0])
    out = [ca[0]]
    for x, y in zip(ca[1:], cc[1:]):
        y = re.sub(r"\\textbf\{(\d+)\}", r"\1", y)
        out.append(x if x == "--" else f"{x} {{\\scriptsize({y})}}")
    print(" & ".join(out) + " \\\\")

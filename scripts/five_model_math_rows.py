"""LaTeX rows of the five-model MATH-500 table: joins the rows of the two paper models (n500_table.py --latex-main) and of
the three added models (new_model_rows.py full math) into one row per method, 8 + 12 budget cells. A cell is set in
grey (\\sigbelow) where the paired-count rows (n500_table.py --latex-pairs, new_model_pairs.py math) mark EpiKV
significantly above it; no dagger is printed. The last row is DMS, a trained policy with one checkpoint (Qwen3-8B) and no
budget, from results/rebuttal_dms.

  five_model_math_rows.py <two-model rows .tex> <three-model rows .tex> <two-model pairs .tex> <three-model pairs .tex>
"""
import glob
import json
import re
import sys
from pathlib import Path

SHORT = {"\\methodq~(ours)": "\\methodq", "\\methodseg~(no query term)": "\\methodseg"}


def rows(path):
    out, order = {}, []
    for line in open(path):
        line = line.strip()
        if not line or line.startswith("%") or line in ("\\midrule", "\\rowcolor{epirow}"):
            continue
        cells = [c.strip() for c in line.rstrip("\\").rstrip().split("&")]
        out[cells[0]] = cells[2:]          # label, FA2 mark, then the budget cells
        order.append((cells[0], cells[1]))
    return out, order


a, order = rows(sys.argv[1])
b, _ = rows(sys.argv[2])
assert set(a) == set(b), (sorted(set(a) ^ set(b)))


def below(path):
    """row label -> one flag per cell: EpiKV is significantly above the row there"""
    out = {}
    for line in open(path):
        line = line.strip()
        if not line or line.startswith("%"):
            continue
        cells = [c.strip() for c in line.rstrip("\\").rstrip().split("&")]
        flags = []
        for c in cells[1:]:
            m = re.match(r"(\d+)/(\d+)(\$\^\{\*+\}\$)?$", c)
            sig = bool(m and m.group(3))
            assert not sig or int(m.group(1)) > int(m.group(2)) or cells[0].startswith("none"), (cells[0], c)
            flags.append(sig)
        out[cells[0]] = flags
    return out


pa, pb = below(sys.argv[3]), below(sys.argv[4])
print("% generated by scripts/five_model_math_rows.py from the two-model and three-model MATH-500 rows")
for label, mark in order:
    cells = [c.replace("$^{\\dagger}$", "") for c in a[label] + b[label]]
    key = SHORT.get(label, label)
    if key in pa and not label.startswith("none"):
        cells = [f"\\sigbelow{{{c}}}" if f else c for c, f in zip(cells, pa[key] + pb[key])]
    if label.startswith("\\methodq"):
        print("\\rowcolor{epirow}")
    print(f"{SHORT.get(label, label)} & {mark} & " + " & ".join(cells) + " \\\\")
    if label.startswith("none") or label == "Lag-KV":
        print("\\midrule")
dms = [p for f in glob.glob(str(Path(__file__).resolve().parent.parent / "results/rebuttal_dms/math_q8b_dms8x_s*.json"))
       for byk in json.load(open(f))["results"].values() for e in byk.values() for p in e["per_problem"]]
assert len(dms) == 495 and not any(p.get("error") for p in dms), len(dms)
none = "\\multicolumn{4}{c}{--}"
print("\\midrule")
print(f"DMS (trained, no budget) & \\xmark & {none} & {none} & \\multicolumn{{4}}{{c}}"
      f"{{{100 * sum(bool(p['correct']) for p in dms) / 495:.1f}}} & {none} & {none} \\\\")

"""LaTeX rows of the five-model MATH-500 table: joins the rows of the two paper models (n500_table.py --latex-main) and of
the three added models (new_model_rows.py full math) into one row per method, 8 + 12 budget cells. Daggers are set in
the column gap (\\rlap) so they add no width.

  five_model_math_rows.py <two-model rows .tex> <three-model rows .tex>
"""
import sys

SHORT = {"\\methodq~(ours)": "\\methodq", "\\methodseg~(no query term)": "\\methodseg"}


def rows(path):
    out, order = {}, []
    for line in open(path):
        line = line.strip()
        if not line or line.startswith("%") or line in ("\\midrule", "\\rowcolor{epirow}"):
            continue
        cells = [c.strip() for c in line.rstrip("\\").rstrip().split("&")]
        out[cells[0]] = cells[2:]          # label, FA2 mark, then the budget cells
        order.append((cells[0], cells[1]))
    return out, order


a, order = rows(sys.argv[1])
b, _ = rows(sys.argv[2])
assert set(a) == set(b), (sorted(set(a) ^ set(b)))
print("% generated by scripts/five_model_math_rows.py from the two-model and three-model MATH-500 rows")
for label, mark in order:
    cells = [c.replace("$^{\\dagger}$", "\\rlap{$^{\\dagger}$}") for c in a[label] + b[label]]
    if label.startswith("\\methodq"):
        print("\\rowcolor{epirow}")
    print(f"{SHORT.get(label, label)} & {mark} & " + " & ".join(cells) + " \\\\")
    if label.startswith("none") or label == "Lag-KV":
        print("\\midrule")

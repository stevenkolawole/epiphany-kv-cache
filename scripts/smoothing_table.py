#!/usr/bin/env python3
"""Rows of tab:smoothing: |rho| of the band layers and KV-key variance with the counterfactual labels under
raw, EMA (alpha=0.9) and rolling-64 smoothing, from results_recovered/*_signal_ablation.csv."""
import csv
from pathlib import Path
R = Path(__file__).resolve().parent.parent
DS = [("math500", "MATH-500"), ("math500_eager", "MATH-500 (eager)"), ("aime2024", "AIME-2024"),
      ("aime2024_eager", "AIME-2024 (eager)")]
SIG = [("hs_l2_diff_l10", "$\\bar g_{10}$ (Band A)"), ("hs_l2_diff_l21", "$\\bar g_{21}$ (Band B)"),
       ("kv_key_var", "KV-key variance")]
rows = ["% |rho| of each signal under three smoothings; generated by scripts/smoothing_table.py"]
for d, dn in DS:
    t = {r["signal"]: float(r["spearman_rho"]) for r in csv.DictReader(open(R / f"results_recovered/{d}_signal_ablation.csv"))}
    for k, (s, sn) in enumerate(SIG):
        v = [t[s], t[s + "_ema09"], t[s + "_rolling64"]]
        rows.append(f"{dn if k == 0 else ''} & {sn} & " + " & ".join(f"{abs(x):.3f}" for x in v) + " \\\\")
    rows.append("\\addlinespace")
(R.parent / "EpiKV-overleaf/tables/tab_smoothing_rows.tex").write_text("\n".join(rows[:-1]) + "\n")
print("\n".join(rows[:-1]))

"""LaTeX rows of paired wins/losses of EpiKV over each row, for the three added models (Qwen3-8B, Qwen3-14B,
Nemotron-Nano-8B; H200, greedy, cap 16,384), on the same cells and problem sets as new_model_rows.py. Cell format as
tab:pairs: wins/losses of EpiKV, star = exact McNemar (* p<0.05, ** p<0.01, *** p<0.001).

  new_model_pairs.py math     MATH-500, K = 512, 1024, 2048, 4096
  new_model_pairs.py gpqa     GPQA-Diamond, K = 1024, 2048, 4096

Also checks that every dagger in tables/tab_new_models_<ds>_rows.tex (if present) sits where EpiKV beats all five attention rows
significantly in these counts; disagreements are written to stderr.
"""
import re
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
from grid_tables import load, pair, star  # noqa: E402
from pool_aime import mcnemar_exact  # noqa: E402
import released_baselines  # noqa: E402

ds = sys.argv[1]
MODELS = ["qwen3", "q14b", "nemo"]
KS = [512, 1024, 2048, 4096] if ds == "math" else [1024, 2048, 4096]
ROWS = ["none", "epikvnoq", "lagkv", "raas", "h2o", "rkv", "longflow", "thinkv"]
NAME = {"none": "none", "epikvnoq": "\\methodseg", "lagkv": "Lag-KV", "raas": "RaaS",
        "h2o": "H2O", "rkv": "R-KV", "longflow": "LongFlow", "thinkv": "ThinKV"}
ATTENTION = ["raas", "h2o", "rkv", "longflow", "thinkv"]
cells, _, _ = load()
MARK = released_baselines.apply(cells, ds, MODELS, KS)   # R-KV from its released code; cells with no released number
def have(p, m, k):
    return bool(cells.get((ds, m, p, 0 if p == "none" else k)))


gone = [p for p in ROWS if p not in ("rkv", "longflow") and not any(have(p, m, k) for m in MODELS for k in KS)]   # as new_model_rows.py: a row with no cell is left out
if gone:
    print(f"row left out, no complete cell for any model: {gone}", file=sys.stderr)
ROWS = [p for p in ROWS if p not in gone]
need = ["epikv"] + ROWS
probs = {}
for m in MODELS:   # same set as new_model_rows.py full: problems present in every row and budget
    s = None
    for p in need:
        for k in ([0] if p == "none" else KS):
            if not have(p, m, k):
                assert p in ("rkv", "longflow"), (ds, m, p, k)   # only released-code rows may lack a cell
                continue
            v = set(cells[(ds, m, p, k)])
            s = v if s is None else s & v
    probs[m] = sorted(s)
res = {}
print(f"% wins/losses of \\methodq over the row, exact McNemar; generated by scripts/new_model_pairs.py {ds}; n = "
      + ", ".join(f"{m} {len(probs[m])}" for m in MODELS))
for p in ROWS:
    row = []
    for m in MODELS:
        for k in KS:
            if not have(p, m, k):
                res[(p, m, k)] = None
                row.append(MARK[(m, p, k)])
                continue
            w, l = pair(cells[(ds, m, "epikv", k)], cells[(ds, m, p, 0 if p == "none" else k)], probs[m])
            pv = mcnemar_exact(len(w), len(l))
            res[(p, m, k)] = len(w) > len(l) and pv < 0.05
            row.append(f"{len(w)}/{len(l)}" + (f"$^{{{'*' * (star(pv).count('*'))}}}$" if star(pv) else ""))
    print(NAME[p] + " & " + " & ".join(row) + " \\\\")
f = Path(__file__).resolve().parent.parent.parent / "EpiKV-overleaf/tables" / f"tab_new_models_{ds}_rows.tex"
if f.exists():
    line = next(l for l in f.read_text().splitlines() if l.startswith("\\methodq~(ours)"))
    daggers = ["dagger" in c for c in line.split(" & ")[2:]]
    mine = [all(res[(p, m, k)] for p in ATTENTION if res.get((p, m, k)) is not None) for m in MODELS for k in KS]
    for (m, k), d, s in zip([(m, k) for m in MODELS for k in KS], daggers, mine):
        if d != s:
            print(f"DAGGER DISAGREES {ds} {m} K={k}: rows file {d}, counts {s}", file=sys.stderr)

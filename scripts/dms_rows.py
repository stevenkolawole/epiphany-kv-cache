"""LaTeX rows for the trained-policy table (Qwen3-8B; DMS = nvidia/Qwen3-8B-DMS-8x, 8x compression, no budget).

MATH-500 (n=495) and GPQA-Diamond (n=198), greedy, cap 16,384: no eviction, EpiKV and RaaS from the pooled H200 grid
(grid_tables.load), DMS from results/rebuttal_dms (uk-p5 H200, sdpa), paired by dataset index with the problem text
checked. AIME 2024-2026 pooled (n=90), cap 32,768, all four from results/rebuttal_aime_qwen3_8b (Babel L40S; one
problem per file, no error). Stars: exact McNemar against EpiKV (* p<0.05, ** p<0.01, *** p<0.001).

  dms_rows.py acc       accuracy rows (layout of tab:dms); stars on the RaaS cells; none and DMS span the budgets
  dms_rows.py pairs     wins/losses of EpiKV over none, DMS and RaaS in every column, with stars
  dms_rows.py report    exact p, n and DMS live-cache means (stdout, not for the paper)
"""
import glob
import json
import re
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
from grid_tables import load, pair, star  # noqa: E402
from pool_aime import mcnemar_exact  # noqa: E402

R = Path(__file__).resolve().parent.parent / "results"
cells, _, _ = load()


def shards(files):
    out = {}
    for f in files:
        s = int(re.search(r"_s(\d+)\.json$", f)[1])
        j = json.load(open(f))
        e = next(iter(next(iter(j["results"].values())).values()))
        assert not e.get("partial"), f
        for i, p in enumerate(e["per_problem"]):
            assert not p.get("error") and p["n_tokens_generated"], (f, i)
            out[s + i] = p
    return out


def aime(tag):
    out = {}
    for d in ("aime2024", "aime2025", "aime2026"):
        for k, p in shards(sorted(glob.glob(str(R / "rebuttal_aime_qwen3_8b" / f"{tag.format(ds=d)}_s*.json")))).items():
            out[(d, k)] = p
    assert len(out) == 90, (tag, len(out))
    return out


COLS = [("math", K) for K in (1024, 2048, 4096)] + [("gpqa", K) for K in (1024, 2048, 4096)] + [("aime", 4096), ("aime", 8192)]
REC = {}   # (policy, ds, K) -> {problem: record}
for ds in ("math", "gpqa"):
    dms = shards(sorted(glob.glob(str(R / "rebuttal_dms" / f"{ds}_q8b_dms8x_s*.json"))))
    REC[("dms", ds, 0)] = dms
    REC[("none", ds, 0)] = cells[(ds, "qwen3", "none", 0)]
    for K in (1024, 2048, 4096):
        for p in ("epikv", "raas"):
            REC[(p, ds, K)] = cells[(ds, "qwen3", p, K)]
    for p in ("dms", "none"):
        r = REC[(p, ds, 0)]
        for q in REC[("epikv", ds, 1024)]:   # same problem at the same index, text checked
            assert r[q]["problem"] == REC[("epikv", ds, 1024)][q]["problem"], (ds, q)
REC[("dms", "aime", 0)] = aime("dms_{ds}_k8")
REC[("none", "aime", 0)] = aime("none_{ds}_k0")
for K in (4096, 8192):
    REC[("epikv", "aime", K)] = aime("kv_seg_hs_fill_{ds}_k" + str(K))
    REC[("raas", "aime", K)] = aime("raas_{ds}_k" + str(K))
for (p, ds, K), r in REC.items():
    assert len(r) == {"math": 495, "gpqa": 198, "aime": 90}[ds], (p, ds, K, len(r))


def get(p, ds, K):
    return REC[(p, ds, 0 if p in ("dms", "none") else K)]


def acc(p, ds, K):
    r = get(p, ds, K)
    return 100 * sum(x["correct"] for x in r.values()) / len(r)


def test(p, ds, K):
    probs = sorted(get("epikv", ds, K))
    w, l = pair(get("epikv", ds, K), get(p, ds, K), probs)
    return len(w), len(l), mcnemar_exact(len(w), len(l))


def stars(pv):
    return f"$^{{{star(pv)}}}$" if star(pv) else ""


mode = sys.argv[1]
if mode == "acc":
    print("% generated by scripts/dms_rows.py acc; MATH-500 n=495, GPQA-Diamond n=198 (H200), AIME n=90 (L40S); "
          "stars: exact McNemar against EpiKV")
    for p, name in (("none", "No eviction"), ("dms", "DMS (trained, $8\\times$)")):
        print(f"{name} & " + " & ".join(f"\\multicolumn{{{n}}}{{c}}{{{acc(p, ds, 0):.1f}}}" for ds, n in (("math", 3), ("gpqa", 3), ("aime", 2))) + " \\\\")
        if p == "dms":
            print("\\midrule")
    for p, name in (("epikv", "\\methodq"), ("raas", "RaaS")):
        print(("\\rowcolor{epirow}" if p == "epikv" else "") + f"{name} & " + " & ".join(
            f"{acc(p, ds, K):.1f}" + ("" if p == "epikv" else stars(test(p, ds, K)[2])) for ds, K in COLS) + " \\\\")
elif mode == "pairs":
    print("% wins/losses of \\methodq over the row, exact McNemar; generated by scripts/dms_rows.py pairs; columns as tab:dms")
    for p, name in (("none", "No eviction"), ("dms", "DMS (trained, $8\\times$)"), ("raas", "RaaS")):
        print(f"{name} & " + " & ".join("{}/{}{}".format(*test(p, ds, K)[:2], stars(test(p, ds, K)[2])) for ds, K in COLS) + " \\\\")
else:
    for ds, K in COLS:
        for p in ("none", "dms", "raas"):
            w, l, pv = test(p, ds, K)
            print(f"{ds} K={K}: EpiKV vs {p}: {w}/{l} p={pv:.4g} n={len(get('epikv', ds, K))}")
    for ds in ("math", "gpqa", "aime"):
        probs = sorted(REC[("none", ds, 0)])
        w, l = pair(REC[("none", ds, 0)], REC[("dms", ds, 0)], probs)
        print(f"{ds}: none over DMS {len(w)}/{len(l)} p={mcnemar_exact(len(w), len(l)):.4g}; acc none {acc('none', ds, 0):.1f} DMS {acc('dms', ds, 0):.1f}")
    for ds in ("math", "gpqa", "aime"):
        kv = [x["kv_live"] for x in REC[("dms", ds, 0)].values()]
        print(f"{ds}: DMS live entries per head, mean over problems of per-problem mean {sum(k['mean_all'] for k in kv) / len(kv):.1f}, "
              f"mean of peaks {sum(k['peak_all'] for k in kv) / len(kv):.1f}")

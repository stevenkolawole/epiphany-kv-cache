"""LaTeX rows of cap hits for the window-rule table (same rows, models and budgets as window_rule_rows.py).

A cap hit is a generation whose generated tokens reach the cap (16,384): the definition of grid_tables.stats and
pair_with_epikv.py. Reads the cap_m / cap_e columns of results/rebuttal_window_rules/paired_with_epikv.txt (every row
has 495 pairs; EpiKV's count is the same in every pairing). Cells are counts out of 495. Usage: window_rule_caps.py
"""
import re
from pathlib import Path

F = Path(__file__).resolve().parent.parent / "results" / "rebuttal_window_rules" / "paired_with_epikv.txt"
ROWS = [("raas_epikv_window", "RaaS's rule on the query read"), ("r_kv_epikv_window", "R-KV's rule on the query read"),
        ("kvpress_snapkv_decoding", "kvpress (SnapKV, decoding)"), ("longflow_native", "LongFlow (released kernel)")]
KS = [512, 1024, 2048, 4096]
cap, epi = {}, {}
for line in F.read_text().splitlines():
    m = re.match(r"(llama|qwen)_(\w+)_K(\d+)\s+(\d+)\s+[\d.]+\s+[\d.]+\s+\d+\s+\d+\s+[\d.]+\s+(\d+)\s+(\d+)\s+\d+", line)
    if not m:
        continue
    model, meth, K, n, cm, ce = m.group(1), m.group(2), int(m.group(3)), *map(int, m.group(4, 5, 6))
    assert n == 495, line
    cap[(model, meth, K)] = cm
    epi.setdefault((model, K), set()).add(ce)
print("% generated by scripts/window_rule_caps.py from results/rebuttal_window_rules/paired_with_epikv.txt; "
      "generations reaching the 16,384 cap, out of 495")
cells = []
for model in ("llama", "qwen"):
    for K in KS:
        assert len(epi[(model, K)]) == 1, (model, K, epi[(model, K)])
        cells.append(str(*epi[(model, K)]))
print("\\rowcolor{epirow}\\methodq & " + " & ".join(cells) + " \\\\")
print("\\midrule")
for meth, label in ROWS:
    print(f"{label} & " + " & ".join(str(cap[(m, meth, K)]) if (m, meth, K) in cap else "--"
                                      for m in ("llama", "qwen") for K in KS) + " \\\\")

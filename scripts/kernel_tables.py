#!/usr/bin/env python3
"""Rows for the kernel-cost tables (appendix "Where the attention matrix costs"):
tab_prefill_latency_rows.tex from reports/prefill_{eager_attn,flash}_a100.json and
tab_decode_step_rows.tex from reports/decode_{eager_attn,flash}_a100.json, each mode
measured in its own process (bench_prefill_memory.py / bench_decode_step.py, one
exclusive A100-40GB, transformers 4.57.1, logits_to_keep=1). Prints the ratios the
captions quote."""
import json
from pathlib import Path

R = Path(__file__).resolve().parent.parent / "reports"
T = Path(__file__).resolve().parent.parent.parent / "EpiKV-overleaf" / "tables"


def load(kind):
    e = json.load(open(R / f"{kind}_eager_attn_a100.json"))
    f = json.load(open(R / f"{kind}_flash_a100.json"))
    assert e["gpu_gb"] == f["gpu_gb"], (e["gpu_gb"], f["gpu_gb"])
    return e["results"]["eager_attn"], f["results"]["flash"], e["gpu_gb"]


def prefill():
    e, f, gb = load("prefill")
    rows = [f"% prefill peak memory and wall time, A100-{round(gb)}GB, transformers 4.57.1, one mode per process;"
            " generated by scripts/kernel_tables.py from reports/prefill_*_a100.json"]
    for n in [512, 1024, 2048, 4096, 8192, 16384, 32768, 65536]:
        k = f"b1_n{n}"
        def cells(r):
            return "OOM & --" if r["oom"] else f"{r['peak_gpu_mb']/1024:.1f} & {r['prefill_s']:.2f}"
        rows.append(f"{n:,} & {cells(e[k])} & {cells(f[k])} \\\\")
        if not e[k]["oom"]:
            print(f"prefill n={n}: eager/flash time {e[k]['prefill_s']/f[k]['prefill_s']:.2f}x, "
                  f"memory {e[k]['peak_gpu_mb']/f[k]['peak_gpu_mb']:.2f}x")
    (T / "tab_prefill_latency_rows.tex").write_text("\n".join(rows) + "\n")


def decode():
    e, f, gb = load("decode")
    rows = [f"% decode-step latency (ms) with a cache of n tokens, batch b, A100-{round(gb)}GB, transformers 4.57.1,"
            " median of five steps after one warm-up; generated by scripts/kernel_tables.py from reports/decode_*_a100.json"]
    for b in (1, 8, 32):
        first = True
        for n in (1024, 2048, 4096, 8192, 16384):
            k = f"b{b}_n{n}"
            if k not in f:
                continue
            fe, ff = e[k], f[k]
            if fe["oom"] and ff["oom"]:
                continue
            ce = "OOM" if fe["oom"] else f"{fe['step_ms']:.1f}"
            cf = "OOM" if ff["oom"] else f"{ff['step_ms']:.1f}"
            ratio = "--" if (fe["oom"] or ff["oom"]) else f"{fe['step_ms']/ff['step_ms']:.2f}"
            lead = f"{b}" if first else ""
            rows.append(f"{lead} & {n:,} & {ce} & {cf} & {ratio} \\\\")
            first = False
            print(f"decode b={b} n={n}: eager {ce} flash {cf} ratio {ratio}")
        rows.append("\\addlinespace")
    if rows[-1] == "\\addlinespace":
        rows.pop()
    (T / "tab_decode_step_rows.tex").write_text("\n".join(rows) + "\n")


if __name__ == "__main__":
    prefill()
    decode()
